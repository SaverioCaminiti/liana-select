/** A value from a label: lower case, ASCII letters and digits, words joined by dashes. */
function toValue(label: string): string {
  return label
    .normalize('NFD')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

/**
 * Builds the <liana-group> / <liana-option> children for a list of entries.
 * Option values come from their labels; when two options would share a value,
 * the later one is prefixed with its group, so that every value is unique.
 */
export function buildChildren(
  entries: MenuEntry[],
  selectedValue?: string,
  used = new Set<string>(),
  groupValue = '',
): Element[] {
  return entries.map((entry) => {
    if (typeof entry === 'string') {
      let value = toValue(entry);
      if (used.has(value)) value = `${groupValue}-${value}`;
      used.add(value);
      const option = document.createElement('liana-option');
      option.value = value;
      option.textContent = entry;
      option.selected = value === selectedValue;
      return option;
    }
    const [label, children] = entry;
    const group = document.createElement('liana-group');
    group.label = label;
    group.append(...buildChildren(children, selectedValue, used, toValue(label)));
    return group;
  });
}
